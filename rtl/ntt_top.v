// ---------------------------------------------------------------------
// ntt_top: parameterized NTT accelerator top level.
//
// Usage:
//   1. With busy==0, write the N input coefficients one at a time via
//      (ext_we, ext_addr, ext_wdata) -- one write per cycle, addr 0..N-1.
//   2. Pulse i_start for one cycle.
//   3. Wait for o_done (single-cycle pulse); the transform is complete
//      and the N result coefficients sit in coeff_mem in place.
//   4. With busy==0, read results one at a time via (ext_addr, ext_rdata)
//      (1-cycle read latency, same as during load).
//
// Re-parameterize N and Q for a different instance; INITFILE must point
// at a matching zeta memory file generated by scripts/gen_zetas.py.
// ---------------------------------------------------------------------
module ntt_top #(
    parameter integer N        = 256,
    parameter integer Q        = 3329,
    parameter integer W        = 12,
    parameter integer AW       = 8,             // = clog2(N)
    parameter integer ZAW      = 7,              // = clog2(N/2)
    parameter          INITFILE = "zetas_N256.mem"
) (
    input  wire           clk,
    input  wire           rst_n,

    // control
    input  wire           i_start,
    output wire            o_busy,
    output wire            o_done,

    // external load/unload port (only honored while o_busy == 0)
    input  wire            ext_we,
    input  wire [AW-1:0]   ext_addr,
    input  wire [W-1:0]    ext_wdata,
    output wire [W-1:0]    ext_rdata
);
    // ---------------- shared coefficient memory ----------------
    wire           fsm_a_we, fsm_b_we;
    wire [AW-1:0]  fsm_a_addr, fsm_b_addr;
    wire [W-1:0]   fsm_a_wdata, fsm_b_wdata;
    wire [W-1:0]   mem_a_rdata, mem_b_rdata;

    wire busy;

    // Port A: shared between external load/unload and the FSM's addr_a.
    // Port B: used only by the FSM for addr_b during a run (idle/unused
    // while loading -- external access only needs one port since it's a
    // simple linear sweep).
    wire           mem_a_we   = busy ? fsm_a_we   : ext_we;
    wire [AW-1:0]  mem_a_addr = busy ? fsm_a_addr : ext_addr;
    wire [W-1:0]   mem_a_wdata= busy ? fsm_a_wdata: ext_wdata;

    wire           mem_b_we    = busy ? fsm_b_we   : 1'b0;
    wire [AW-1:0]  mem_b_addr  = busy ? fsm_b_addr : {AW{1'b0}};
    wire [W-1:0]   mem_b_wdata = fsm_b_wdata;

    assign ext_rdata = mem_a_rdata;

    coeff_mem #(.N(N), .W(W), .AW(AW)) u_mem (
        .clk     (clk),
        .a_we    (mem_a_we),   .a_addr (mem_a_addr), .a_wdata (mem_a_wdata), .a_rdata (mem_a_rdata),
        .b_we    (mem_b_we),   .b_addr (mem_b_addr), .b_wdata (mem_b_wdata), .b_rdata (mem_b_rdata)
    );

    ntt_fsm #(.N(N), .Q(Q), .W(W), .AW(AW), .ZAW(ZAW), .INITFILE(INITFILE)) u_fsm (
        .clk (clk), .rst_n (rst_n),
        .i_start (i_start), .o_busy (busy), .o_done (o_done),
        .mem_a_we (fsm_a_we), .mem_a_addr (fsm_a_addr), .mem_a_wdata (fsm_a_wdata), .mem_a_rdata (mem_a_rdata),
        .mem_b_we (fsm_b_we), .mem_b_addr (fsm_b_addr), .mem_b_wdata (fsm_b_wdata), .mem_b_rdata (mem_b_rdata)
    );

    assign o_busy = busy;
endmodule
